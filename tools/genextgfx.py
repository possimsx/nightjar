"""Generate BanksExtGfx.asm: the extended-tileset banks (gfx ids 8-15).

Multi-bank layout (content-driven): a single CONTROL segment (10h, always mapped
to #6000 by ExtDivert) holds idxTileSetsExt + every TileSetExt config + the
SegBaseExt table + IdxColisTilesExt + every CollTilesExt + LoadExtDispatch. Each
tileset then gets its OWN gfx segment (11h, 12h, ...) which the dispatcher maps
into #8000/#A000 per-load using SegBaseExt. So each ext tileset has a full ~8KB
(256-tile) budget instead of all of them sharing one 24KB window.

The ROM grows one segment per ext tileset; the adaptive sizer (tools/build.py)
picks 128/256/512KB from the result. ExtDivert in Banks0123.asm is UNCHANGED
(it still maps base 10h and rets into LoadExtDispatch).

Usage:  python tools/genextgfx.py [--tilesets N]   (default 1 = gfx id 8 only)

Tileset 8 starts as an editable clone of Building; any extras (--tilesets >1)
are additional Building clones as placeholders for new art.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # .../tools
import mgmap, mgrender, mggfx, mgproj
CONTROL_SEG = 0x10           # first ext segment = control (index/config/collision/dispatch)
GFX_SEG0 = 0x11              # first per-tileset gfx segment

NTS = 1
if "--tilesets" in sys.argv:
    NTS = max(1, int(sys.argv[sys.argv.index("--tilesets") + 1]))

# Building clone gfx (block 1 = 135 tiles, block 2 = 40 tiles over-reading into
# GfxBasemDesert2 exactly as the stock tileset does) + its collision bitmap.
gb = mggfx.parse_block(mgrender.find_gfx_file("GfxBuilding"), "GfxBuilding")
gb2 = (mggfx.parse_block(mgrender.find_gfx_file("GfxBuilding2"), "GfxBuilding2") +
       mggfx.parse_block(mgrender.find_gfx_file("GfxBasemDesert2"), "GfxBasemDesert2"))[:960]
coll = mgmap.parse_flat(mgmap._read("data/roomtileset.asm"), "CollTilesBuilding")
assert len(coll) == 32, len(coll)
assert len(gb) + len(gb2) <= 8192, "one tileset's gfx must fit a single 8KB segment"


def dbblock(label, data, perline=16):
    out = []
    for k in range(0, len(data), perline):
        toks = ", ".join(mggfx._tok(b) for b in data[k:k + perline])
        out.append((("%-20sdb\t" % (label + ":")) if k == 0 else "\t\t    db\t") + toks)
    return out


L = []
A = L.append
A(";----------------------------------------------------------------------------")
A("; NIGHTJAR: extended tilesets (gfx ids 8-15). Multi-bank: control seg 10h +")
A("; one gfx segment per tileset (11h, 12h, ...). Reached from ExtDivert (Banks0123")
A("; header gap) when a room's gfx-tileset >= 8. Tileset 8 = editable Building clone.")
A("; LoadExtDispatch maps the tileset's gfx seg to #8000/#A000 (SegBaseExt) then")
A("; mirrors LoadRoomTiles' block + collision load via the stock seg-0 helpers.")
A("; Generated by tools/genextgfx.py.")
A(";----------------------------------------------------------------------------")
A("")
A("\t\t    org\t#6000\t\t\t    ; control segment (10h), always mapped to #6000")
A("")

# --- index of tileset configs (gfx id 8 + NTS-1) ---
A("idxTileSetsExt:" + "".join(
    "\t    dw TileSetExt%d%s\n" % (t, "\t\t    ; gfx id %d" % (8 + t)) for t in range(NTS)).rstrip("\n"))
A("")
# --- gfx base segment for each ext tileset (mapped into #8000/#A000 per-load) ---
A("SegBaseExt:\t    db " + ", ".join("%02Xh" % (GFX_SEG0 + t) for t in range(NTS))
  + "\t    ; tileset gfx segments")
A("")
A("IdxColisTilesExt:" + "".join(
    "   dw CollTilesExt%d\n" % t for t in range(NTS)).rstrip("\n"))
A("")

# --- per-tileset config blocks (gfx pointers resolve into the #8000 window) ---
for t in range(NTS):
    g0, g1 = "GfxExt%d" % (2 * t), "GfxExt%d" % (2 * t + 1)
    A("TileSetExt%d:\t    db 1" % t)
    A("\t\t    db 87h")
    A("\t\t    db 3")
    A("\t\t    dw %s" % g0)
    A("\t\t    db 21h")
    A("\t\t    db 28h")
    A("\t\t    db 0A8h")
    A("\t\t    dw %s" % g1)
    A("\t\t    db 41h")
    A("\t\t    db 0D8h")
    A("")

# --- per-tileset collision bitmaps ---
for t in range(NTS):
    L += dbblock("CollTilesExt%d" % t, coll)
    A("")

# --- dispatcher: ExtDivert mapped 10h->#6000/11h->#8000/12h->#A000 and RETs here.
#     Remap #8000/#A000 to THIS tileset's gfx segment, then load. Stack = [caller_ret]. ---
A(";--- dispatcher: maps the tileset's gfx seg to #8000/#A000 (BankIn shadows kept),")
A(";    then loads the config blocks + collision. di is in effect from ExtDivert. ---")
A("LoadExtDispatch:")
A("\t\t    ld\t    a, (CurrentTileSet)")
A("\t\t    sub\t    8\t\t\t\t    ; ext tileset index")
A("\t\t    ld\t    e, a")
A("\t\t    ld\t    d, 0")
A("\t\t    ld\t    hl,	SegBaseExt")
A("\t\t    add\t    hl,	de")
A("\t\t    ld\t    a, (hl)\t\t\t    ; gfx base segment for this tileset")
A("\t\t    ld\t    (8000h), a\t\t\t    ; map it to #8000 (control stays at #6000)")
A("\t\t    ld\t    (BankIn80),	a")
A("\t\t    inc\t    a")
A("\t\t    ld\t    (0A000h), a\t\t\t    ; base+1 to #A000")
A("\t\t    ld\t    (BankInA0),	a")
A("\t\t    ld\t    a, (CurrentTileSet)")
A("\t\t    sub\t    8")
A("\t\t    ld\t    de,	idxTileSetsExt")
A("\t\t    call    GetPointerDE2A\t\t    ; DE = ext config pointer (seg 10h)")
A("\t\t    push    de")
A("\t\t    pop\t    ix")
A("\t\t    ld\t    b, 3")
A("LExtBlk:")
A("\t\t    ld\t    a, (ix+0)")
A("\t\t    rla\t\t\t\t\t    ; bit7 = load collision?")
A("\t\t    jr\t    c, LExtCol")
A("\t\t    call    LoadTileset")
A("\t\t    ld\t    de,	5")
A("\t\t    add\t    ix,	de")
A("\t\t    djnz    LExtBlk")
A("LExtCol:")
A("\t\t    ld\t    a, (CurrentTileSet)")
A("\t\t    sub\t    8")
A("\t\t    ld\t    hl,	CollisionTiles")
A("\t\t    exx")
A("\t\t    ld\t    hl,	IdxColisTilesExt")
A("\t\t    call    ADD_HL_2A")
A("\t\t    ld\t    a, (hl)")
A("\t\t    inc\t    hl")
A("\t\t    ld\t    h, (hl)")
A("\t\t    ld\t    l, a")
A("\t\t    ld\t    c, 32")
A("LExtCol2:")
A("\t\t    ld\t    a, (hl)")
A("\t\t    exx")
A("\t\t    ld\t    b, 8")
A("LExtCol3:")
A("\t\t    rlca")
A("\t\t    ld\t    d, a")
A("\t\t    and\t    1")
A("\t\t    ld\t    (hl), a")
A("\t\t    ld\t    a, d")
A("\t\t    inc\t    l")
A("\t\t    djnz    LExtCol3")
A("\t\t    exx")
A("\t\t    inc\t    hl")
A("\t\t    dec\t    c")
A("\t\t    jr\t    nz,	LExtCol2")
A("\t\t    jp\t    SetBanks1_2_3		    ; restore banks 1,2,3, ei, ret to caller")
A("")
A("\t\t    ds\t    (#8000-$), #ff\t\t    ; pad control to the end of segment 10h")
A("")

# --- per-tileset gfx segments (each org #8000, padded to one 8KB segment) ---
for t in range(NTS):
    A("; --- gfx for tileset %d (gfx id %d), segment %02Xh ---" % (t, 8 + t, GFX_SEG0 + t))
    A("\t\t    org\t#8000")
    L += dbblock("GfxExt%d" % (2 * t), gb)
    A("")
    L += dbblock("GfxExt%d" % (2 * t + 1), gb2)
    A("\t\t    ds\t    (#A000-$), #ff\t\t    ; fill remainder of this gfx segment")
    A("")

open(mgproj.path("BanksExtGfx.asm"), "w", encoding="latin-1").write("\n".join(L) + "\n")
print("wrote BanksExtGfx.asm: %d tileset(s) (gfx ids 8..%d), control seg 10h + %d gfx seg(s)"
      % (NTS, 7 + NTS, NTS))
