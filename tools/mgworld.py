#!/usr/bin/env python3
"""
mgworld.py - multi-world generator for NIGHTJAR (docs/LIMITS-PLAN.md Phase D2).

A "world" is a parallel copy of the per-room dataset (layouts, connections,
items, actors, doors, radio) in its own 3 ROM segments (data + 2 layout).
The engine reads every top-level table through the world DIRECTORY at the
start of each segment (WDIR_*/LDIR_* in features.asm), so worlds lay out
their content freely; rooms stay 0..250 per world and gateways (door dest
bytes 252-254 + the GatewayTable) hop between worlds.

`gen N` clones the CURRENT world-0 data files into data/worldN/ with all
locally-defined labels suffixed _wN, emits BanksWorldN.asm (directory +
includes + pads), wires the include into MetalGear.asm and bumps the WORLDS
equ in features.asm. Idempotent: refuses to overwrite without --force.

CLI:  python tools/mgworld.py gen 1 [--force]
"""
import os, re, sys, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mgproj                     # active-project resolver (docs/PROJECTS-PLAN.md)

# world-0 source files, in data-segment include order + the layout file.
# pathindex.asm references Paths_* labels defined in the SHARED data/paths.asm
# (not in this set), so suffix_labels leaves those refs pointing at the one
# route pool in Banks456 - by design (docs/LIMITS-PLAN.md D4).
DATA_FILES = ["gateways.asm", "actorsinrooms.asm", "itemsinrooms.asm",
              "roomconnsfull.asm", "radiocalls.asm", "doors.asm",
              "pathindex.asm", "checkpoints.asm"]
LAYOUT_FILE = "rooms.asm"
ALL_FILES = DATA_FILES + [LAYOUT_FILE]

# directory slots (must match WDIR_*/LDIR_* in features.asm)
WDIR = ["idxActorsRooms", "idxRoomItemsIdx", "idxRoomItems", "idxDoors",
        "IdDoorsLogic", "DoorOpenEnterDat", "idxRoomRadio", "RoomConnsFull",
        "GatewayTable", "idxRoomPaths", "SaveStatRooms"]
LDIR = ["idxRooms", "MetaTileSetIDs", "idxMetatileSet"]

LABEL_RE = re.compile(r'^(\w+):', re.M)


def _read(rel):
    return open(mgproj.path(rel), encoding="latin-1").read()


def _write(rel, s):
    path = mgproj.path(rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="latin-1").write(s)


def suffix_labels(sources, n):
    """All labels DEFINED anywhere in the world file set get _wN, both at
    definition and reference sites. External names (Metatiles*, ID_*, enums,
    engine labels) are untouched because they are not defined here."""
    defined = set()
    for s in sources.values():
        defined.update(LABEL_RE.findall(s))
    pat = re.compile(r'\b(' + '|'.join(sorted(defined, key=len, reverse=True)) + r')\b')
    return {f: pat.sub(lambda m: m.group(1) + "_w%d" % n, s) for f, s in sources.items()}


def gen(n, force=False):
    if n < 1:
        sys.exit("world 0 is the canonical data/ set; N must be >= 1")
    outdir = "data/world%d" % n
    bank = "BanksWorld%d.asm" % n
    if os.path.exists(mgproj.path(outdir)) and not force:
        sys.exit("%s already exists (use --force to regenerate)" % outdir)

    src = {f: _read("data/" + f) for f in ALL_FILES}
    out = suffix_labels(src, n)
    for f in ALL_FILES:
        _write("%s/%s" % (outdir, f), out[f])

    w = lambda lab: "%s_w%d" % (lab, n)
    lines = [
        ";----------------------------------------------------------------------------",
        "; World %d (GENERATED by tools/mgworld.py - regenerate rather than hand-edit" % n,
        "; the structure; the data/world%d/*.asm CONTENT is the authoring surface)." % n,
        "; Same 3-segment shape as BanksWorld.asm: data seg + 2 layout segs, each",
        "; starting with the pointer directory the engine reads (features.asm WDIR/LDIR).",
        ";----------------------------------------------------------------------------",
        "",
        "\t    org\t    #6000",
        "",
    ]
    lines += ["\t\t    dw\t    %s" % w(lab) for lab in WDIR]
    lines += ["\t\t    ds\t    32-%d, 0FFh" % (2 * len(WDIR)),
              "",
              "; gateway resolver at the fixed WGATE offset (#6020)",
              "%s:" % w("WorldGate"),
              "\tinclude\t\"hooks/worldgate.asm\"",
              ""]
    lines += ["\tinclude\t\"data/world%d/%s\"\n" % (n, f) for f in DATA_FILES]
    lines += ["\t\t    ds\t    (#8000-$),#ff",
              "\t\t    ASSERT  $=#8000",
              "",
              "\t    org\t    #6000",
              ""]
    lines += ["\t\t    dw\t    %s" % w(lab) for lab in LDIR]
    lines += ["\t\t    ds\t    8-%d, 0FFh" % (2 * len(LDIR)),
              "",
              "\tinclude\t\"data/world%d/%s\"" % (n, LAYOUT_FILE),
              "",
              "\t\t    ds\t    (#0A000-$),#ff",
              "\t\t    ASSERT  $=#0A000",
              ""]
    _write(bank, "\n".join(lines))

    # wire into MetalGear.asm (idempotent)
    mg = _read("MetalGear.asm")
    inc = '\t\tinclude\t"%s"' % bank
    if bank not in mg:
        anchor = '\t\tinclude\t"BanksWorld.asm"\t; world-data bank (items/actors), seg WORLD_SEG\n\t\tENDIF'
        assert anchor in mg, "BanksWorld include anchor not found"
        mg = mg.replace(anchor, anchor.replace("\n\t\tENDIF",
              "\n\n\t\tIF (WORLDS-%d >= 0)\n%s\t; world %d (generated)\n\t\tENDIF\n\t\tENDIF"
              % (n, inc, n)))
        _write("MetalGear.asm", mg)

    # bump WORLDS in features.asm
    ft = _read("features.asm")
    m = re.search(r'^(WORLDS\s+equ\s+)(\d+)', ft, re.M)
    if not m:
        ft = ft.replace("WORLD_LSEG2",
                        "WORLDS\tequ\t%d\t; number of worlds assembled (world 0 + generated)\nWORLD_LSEG2" % (n + 1), 1)
    elif int(m.group(2)) < n + 1:
        ft = ft[:m.start(2)] + str(n + 1) + ft[m.end(2):]
    _write("features.asm", ft)
    print("world %d generated: %s + %s (WORLDS bumped; rebuild to apply)" % (n, outdir, bank))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("n", type=int)
    g.add_argument("--force", action="store_true")
    a = ap.parse_args()
    gen(a.n, force=a.force)
